let lang = 'ko';

function readStored() {
  try {
    return globalThis.localStorage?.getItem(SHOP.langKey) === 'en' ? 'en' : 'ko';
  } catch {
    return 'ko';
  }
}

export function getLang() {
  return lang;
}

export function initLang() {
  lang = readStored();
  applyDocumentLang();
}

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'ko';
  try { globalThis.localStorage?.setItem(SHOP.langKey, lang); } catch { /* Language preference only. */ }
  applyDocumentLang();
}

function applyDocumentLang() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = lang === 'en' ? 'en' : 'ko';
}

export function t(key, vars) {
  const table = lang === 'en' ? en : ko;
  let text = table[key] ?? ko[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function uxError(message) {
  const key = ERROR_KEYS[message];
  return key ? t(key) : String(message ?? '');
}

export function money(value) {
  return formatMoney(value, lang);
}

export function localizedProduct(product) {
  if (!product || lang !== 'en') return product;
  const extra = PRODUCT_EN[product.id];
  if (!extra) return product;
  return {
    ...product,
    name: extra.name,
    short: extra.short,
    description: extra.description,
    variants: product.variants.map(variant => ({ ...variant, name: extra.variants[variant.id] ?? variant.name })),
    details: extra.details,
  };
}

export function localizedFaqs() {
  return lang === 'en' ? FAQS_EN : FAQS;
}

export function langToggleHtml() {
  return `<div class="lang-toggle" role="group" aria-label="${escapeHtml(t('lang.label'))}"><button type="button" data-action="lang" data-lang="ko" aria-pressed="${lang === 'ko'}">KO</button><button type="button" data-action="lang" data-lang="en" aria-pressed="${lang === 'en'}">EN</button></div>`;
}

export function applyStaticCopy() {
  if (typeof document === 'undefined') return;
  document.title = t('meta.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.description'));
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const value = t(el.dataset.i18n);
    const attr = el.dataset.i18nAttr;
    if (attr) el.setAttribute(attr, value);
    else el.textContent = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('.lang-toggle [data-lang]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.lang === lang));
  });
  document.querySelectorAll('.lang-toggle').forEach(group => {
    group.setAttribute('aria-label', t('lang.label'));
  });
}
