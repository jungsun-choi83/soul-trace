export type PetFirstCopy = Copy;

export function petFirstCopy(lang: Locale): PetFirstCopy {
  return lang === "en" ? EN : KO;
}

export function withKoreanWa(name: string): string {
  const code = name.charCodeAt(name.length - 1);
  const hangul = code >= 0xac00 && code <= 0xd7a3;
  return `${name}${hangul && (code - 0xac00) % 28 !== 0 ? "과" : "와"}`;
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/%([A-Z]+)%/g, (match, key: string) => (key in values ? String(values[key]) : match));
}
